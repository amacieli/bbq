# PlatformIO pre-build script: stamp every build with yyyymmdd-hh-mm (local time, 24h) in src/version.h
from datetime import datetime
Import("env")
ver = datetime.now().strftime("%Y%m%d-%H-%M")
with open(env.subst("$PROJECT_DIR/src/version.h"), "w") as f:
    f.write('#pragma once\n// AUTO-GENERATED by scripts/version.py - do not edit\n#define BUILD_VERSION "%s"\n' % ver)
print("BBQ build version:", ver)
